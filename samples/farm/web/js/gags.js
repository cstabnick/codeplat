// KINDS is the list of kinds, in the order LINES defines them.
export const KINDS = Object.keys(LINES);

// The last line returned for each kind, so pickLine never repeats it.
const last = new Map();

// pickLine returns a random line of that kind, never the line returned last time for the same
// kind. An unknown kind returns '...'.
export function pickLine(kind, rng) {
  if (!Object.prototype.hasOwnProperty.call(LINES, kind)) return '...';
  const lines = LINES[kind];
  const previous = last.get(kind);
  let line = rng.pick(lines);
  if (lines.length > 1) {
    while (line === previous) line = rng.pick(lines);
  }
  last.set(kind, line);
  return line;
}
